"""Beacon v2: the daily loop that keeps people coming back and getting better.

The preparation app stores *what* a person is preparing for (profile, skills,
assessments, plan). This app stores *how their learning is going*:

    RoleBlueprint   the skills any role needs, generated once per role title
                    and shared, so "ICU nurse" works as well as "SWE intern"
    SkillMemory     one per person per skill: strength plus a forgetting
                    curve, so Beacon knows what is fading and when to review
    Card            one practice item, written fresh for this person each
                    time, so a retry tests understanding, not recall of the
                    last answer key
    DayLog          one row per active day: mood, cards done, XP
    InterviewSession  a voice or typed mock interview and its STAR report
"""

from datetime import timedelta

from django.db import models
from django.utils import timezone

from preparation.models import CandidateProfile, Skill

# A skill is "due" when the chance of still remembering it drops to this.
TARGET_RETENTION = 0.85


class RoleBlueprint(models.Model):
    """What a role demands, as a list of skills with the bar for each."""

    class Source(models.TextChoices):
        AI = "AI", "Generated by AI"
        PRESET = "PRESET", "Built-in preset"

    slug = models.SlugField(max_length=140, unique=True)
    title = models.CharField(max_length=140)
    summary = models.TextField(blank=True)
    # [{"name", "category", "required", "why"}]
    skills = models.JSONField(default=list)
    source = models.CharField(max_length=6, choices=Source.choices, default=Source.PRESET)
    model_label = models.CharField(max_length=80, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return self.title


class SkillMemory(models.Model):
    """How strong a skill is and how fast it fades.

    retention(t) = 0.85 ** (days since practice / stability)

    so `stability` is the number of days until the chance of recall falls to
    85%, which is exactly when the skill becomes due. A good review stretches
    stability (the next gap is longer); a poor one shrinks it. That is the
    spacing effect, and it is what makes practice stick.
    """

    candidate = models.ForeignKey(
        CandidateProfile, on_delete=models.CASCADE, related_name="memories"
    )
    skill = models.ForeignKey(Skill, on_delete=models.CASCADE, related_name="memories")
    strength = models.FloatField(default=30, help_text="Demonstrated level, 0-100.")
    required = models.PositiveSmallIntegerField(default=65)
    stability = models.FloatField(default=1.0, help_text="Days until recall drops to 85%.")
    last_practiced = models.DateTimeField(null=True, blank=True)
    due_at = models.DateTimeField(default=timezone.now)
    reps = models.PositiveIntegerField(default=0)
    lapses = models.PositiveIntegerField(default=0)

    class Meta:
        constraints = [
            models.UniqueConstraint(fields=["candidate", "skill"], name="one_memory_per_skill")
        ]
        ordering = ["due_at"]

    def __str__(self):
        return f"{self.candidate} · {self.skill}"

    def retention(self, now=None):
        if not self.last_practiced:
            return 1.0
        now = now or timezone.now()
        days = max((now - self.last_practiced).total_seconds() / 86400, 0)
        return TARGET_RETENTION ** (days / max(self.stability, 0.1))

    def effective(self, now=None):
        """Strength discounted by forgetting: what you'd show if asked today.
        Forgetting never takes more than half of what you built."""
        return self.strength * (0.5 + 0.5 * self.retention(now))

    def is_due(self, now=None):
        return self.due_at <= (now or timezone.now())

    def readiness(self, now=None):
        return min(self.effective(now) / self.required, 1.0) if self.required else 1.0

    def record(self, score, now=None, weight=1.0):
        """Apply one practice result (0-100).

        weight < 1 for weaker evidence: picking the right option out of four
        shows less than producing an answer from scratch."""
        now = now or timezone.now()
        # Strength moves part of the way toward what was shown, in either
        # direction, faster while there is little evidence.
        rate = (0.4 if self.reps < 3 else 0.25) * weight
        self.strength = round(self.strength + (score - self.strength) * rate, 1)
        if score >= 60:
            # Better answers and reviews closer to the forgetting point both
            # earn longer gaps, as in SM-2 / FSRS style schedulers.
            ease = 1.6 + (score - 60) / 40          # 1.6 .. 2.6
            boost = 1.0 + 0.5 * (1 - self.retention(now))
            self.stability = min(self.stability * ease * boost, 120)
        else:
            self.lapses += 1
            self.stability = max(self.stability * 0.5, 0.5)
        self.reps += 1
        self.last_practiced = now
        self.due_at = now + timedelta(days=self.stability)


class Card(models.Model):
    """One practice item, written for one person at one moment."""

    class Kind(models.TextChoices):
        CHOICE = "CHOICE", "Multiple choice"
        SHORT = "SHORT", "Short answer"
        STORY = "STORY", "STAR story"
        SCENARIO = "SCEN", "Scenario"

    candidate = models.ForeignKey(CandidateProfile, on_delete=models.CASCADE, related_name="cards")
    skill = models.ForeignKey(Skill, on_delete=models.CASCADE, related_name="cards")
    kind = models.CharField(max_length=6, choices=Kind.choices)
    prompt = models.TextField()
    # CHOICE: {"options": [...], "answer": i, "why": "..."}
    # others: {"key_points": [...], "model_answer": "..."}
    payload = models.JSONField(default=dict)
    difficulty = models.PositiveSmallIntegerField(default=2)
    is_review = models.BooleanField(default=False)
    source = models.CharField(max_length=10, default="ai")
    created_at = models.DateTimeField(auto_now_add=True)
    answered_at = models.DateTimeField(null=True, blank=True)
    response = models.JSONField(null=True, blank=True)
    score = models.PositiveSmallIntegerField(null=True, blank=True)
    feedback = models.JSONField(null=True, blank=True)
    xp = models.PositiveSmallIntegerField(default=0)

    class Meta:
        ordering = ["created_at"]

    def __str__(self):
        return self.prompt[:60]

    @property
    def answered(self):
        return self.answered_at is not None


class DayLog(models.Model):
    class Mood(models.TextChoices):
        GREAT = "GREAT", "Feeling great"
        OK = "OK", "Steady"
        ROUGH = "ROUGH", "Rough day"

    candidate = models.ForeignKey(CandidateProfile, on_delete=models.CASCADE, related_name="days")
    date = models.DateField(default=timezone.localdate)
    mood = models.CharField(max_length=5, choices=Mood.choices, blank=True)
    cards_done = models.PositiveSmallIntegerField(default=0)
    interviews_done = models.PositiveSmallIntegerField(default=0)
    xp = models.PositiveIntegerField(default=0)
    # Snapshot of overall readiness at the end of the day's activity, so the
    # progress chart shows what really happened rather than a reconstruction.
    readiness = models.PositiveSmallIntegerField(null=True, blank=True)

    class Meta:
        constraints = [
            models.UniqueConstraint(fields=["candidate", "date"], name="one_log_per_day")
        ]
        ordering = ["-date"]

    @property
    def active(self):
        return self.cards_done > 0 or self.interviews_done > 0


class InterviewSession(models.Model):
    class Mode(models.TextChoices):
        BEHAVIORAL = "BEHAV", "Behavioral"
        ROLE = "ROLE", "Role-specific"
        MIXED = "MIXED", "Mixed"

    candidate = models.ForeignKey(
        CandidateProfile, on_delete=models.CASCADE, related_name="interviews"
    )
    mode = models.CharField(max_length=5, choices=Mode.choices, default=Mode.MIXED)
    role = models.CharField(max_length=140)
    # [{"who": "interviewer" | "you", "text": "...", "q": 1}]
    transcript = models.JSONField(default=list)
    planned_questions = models.PositiveSmallIntegerField(default=4)
    report = models.JSONField(null=True, blank=True)
    score = models.PositiveSmallIntegerField(null=True, blank=True)
    started_at = models.DateTimeField(auto_now_add=True)
    finished_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        ordering = ["-started_at"]

    @property
    def questions_asked(self):
        return len({t.get("q") for t in self.transcript if t.get("who") == "interviewer"})


class Preferences(models.Model):
    """Per-person settings. Reminders are opt-in: a safe space doesn't nag."""

    candidate = models.OneToOneField(
        CandidateProfile, on_delete=models.CASCADE, related_name="preferences"
    )
    email_reminders = models.BooleanField(default=False)
    last_reminded = models.DateField(null=True, blank=True)

    def __str__(self):
        return f"Preferences for {self.candidate}"


def level_name(value):
    """A friendly name for a 0-100 level."""
    for floor, name in ((85, "Interview-ready"), (70, "Strong"), (55, "Capable"),
                        (35, "Building"), (0, "Starting out")):
        if value >= floor:
            return name
    return "Starting out"


def xp_level(total_xp):
    """Account level from XP: each level needs a bit more than the last."""
    level, need, left = 1, 120, total_xp
    while left >= need:
        left -= need
        level += 1
        need = int(need * 1.25)
    return level, left, need


def clamp(value, low=0, high=100):
    return max(low, min(high, value))
